package cli

import (
	"bufio"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var resourceMarkerPattern = regexp.MustCompile("^// copytygo:resource ([A-Za-z_][A-Za-z0-9_]*)$")
var resourceAccessMarkerPattern = regexp.MustCompile("^// copytygo:resource-access ([a-z]+)$")
var defaultRolePattern = regexp.MustCompile("(?m)^const DefaultRole = \"([^\"]*)\"$")

type generatedResourceRoute struct {
	Resource       string
	ControllerType string
	Access         string
}

type resourceAuthMode struct {
	Kind  string // browser, bearer or none
	Multi bool
}

// detectResourceAuth fails closed for missing, partial, or unrecognized auth
// installation files. Nothing should infer a trusted principal from a UI file.
func detectResourceAuth(root string) resourceAuthMode {
	web, err := os.ReadFile(filepath.Join(root, "app", "auth", "web.go"))
	if err != nil || !strings.Contains(string(web), "func Sessions()") {
		return resourceAuthMode{Kind: "none"}
	}
	role := defaultRolePattern.FindStringSubmatch(string(web))
	if len(role) != 2 || (role[1] != "" && role[1] != "user") {
		return resourceAuthMode{Kind: "none"}
	}
	routes, err := os.ReadFile(filepath.Join(root, "routes", "auth.go"))
	if err != nil || !strings.Contains(string(routes), "func RegisterAuth(") {
		return resourceAuthMode{Kind: "none"}
	}
	kind := "bearer"
	if strings.Contains(string(routes), "appauth.Sessions()") && fileExists(filepath.Join(root, "frontend", "auth.html")) {
		kind = "browser"
	}
	return resourceAuthMode{Kind: kind, Multi: role[1] == "user"}
}

func effectiveResourceAccess(access string, auth resourceAuthMode) string {
	if access == "public" {
		return "public" // only an explicit marker allows unauthenticated CRUD
	}
	if auth.Kind == "none" {
		return "locked"
	}
	if access == "default" {
		if auth.Multi {
			return "admin"
		}
		return "authenticated"
	}
	if (access == "admin" || access == "user") && !auth.Multi {
		return "locked"
	}
	if !validResourceAccess(access) {
		return "locked"
	}
	return access
}

func GenerateResourceRoutes(root string) error {
	module, err := projectModule(filepath.Join(root, "go.mod"))
	if err != nil {
		return err
	}
	controllerDir := filepath.Join(root, "app", "controllers")
	entries, err := os.ReadDir(controllerDir)
	if err != nil {
		return fmt.Errorf("copytygo: unable to read controllers: %w", err)
	}
	resources := make([]generatedResourceRoute, 0)
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".go" {
			continue
		}
		file, err := os.Open(filepath.Join(controllerDir, entry.Name()))
		if err != nil {
			return err
		}
		scanner := bufio.NewScanner(file)
		resource, controllerType, access := "", "", "default"
		for scanner.Scan() {
			line := strings.TrimSpace(scanner.Text())
			if matches := resourceMarkerPattern.FindStringSubmatch(line); len(matches) == 2 {
				resource = matches[1]
			}
			if matches := resourceAccessMarkerPattern.FindStringSubmatch(line); len(matches) == 2 {
				access = matches[1]
			}
			if strings.HasPrefix(line, "type ") && strings.Contains(line, "Controller struct") {
				fields := strings.Fields(line)
				if len(fields) >= 2 {
					controllerType = fields[1]
				}
			}
		}
		_ = file.Close()
		if err := scanner.Err(); err != nil {
			return err
		}
		if resource != "" && controllerType != "" {
			resources = append(resources, generatedResourceRoute{Resource: resource, ControllerType: controllerType, Access: access})
		}
	}
	sort.Slice(resources, func(i, j int) bool { return resources[i].Resource < resources[j].Resource })
	if err := os.MkdirAll(filepath.Join(root, "routes"), 0755); err != nil {
		return err
	}
	auth := detectResourceAuth(root)
	anyProtected, anyBrowserUser := false, false
	for _, item := range resources {
		access := effectiveResourceAccess(item.Access, auth)
		if access != "public" && access != "locked" {
			anyProtected = true
		}
		if auth.Kind == "browser" && access == "user" {
			anyBrowserUser = true
		}
	}

	var builder strings.Builder
	builder.WriteString("// Code generated by CopyTyGo. DO NOT EDIT.\n\npackage routes\n\n")
	builder.WriteString("import (\n")
	if len(resources) > 0 {
		builder.WriteString(fmt.Sprintf("\t%q\n", module+"/app/controllers"))
	}
	builder.WriteString("\t\"github.com/arfajhf/copytygo/v5/core\"\n")
	if anyProtected {
		if auth.Kind == "browser" {
			builder.WriteString(fmt.Sprintf("\tappauth %q\n", module+"/app/auth"))
			if anyBrowserUser {
				builder.WriteString("\tcopyauth \"github.com/arfajhf/copytygo/v5/auth\"\n")
			}
		} else if auth.Kind == "bearer" {
			builder.WriteString("\tcopyauth \"github.com/arfajhf/copytygo/v5/auth\"\n")
		}
	}
	builder.WriteString(")\n\n")
	builder.WriteString("func RegisterGeneratedResources(app *core.Application) {\n")
	if anyProtected && auth.Kind == "browser" {
		builder.WriteString("\tsessions := appauth.Sessions()\n")
	}
	for _, item := range resources {
		access := effectiveResourceAccess(item.Access, auth)
		target := fmt.Sprintf("%q, controllers.%s{}", "/"+item.Resource, item.ControllerType)
		switch access {
		case "public":
			builder.WriteString("\tapp.Resource(" + target + ")\n")
		case "locked":
			builder.WriteString("\tapp.ResourceWithMiddleware(" + target +
				", []core.Middleware{core.ResourceAccessUnconfigured()}, nil)\n")
		default:
			var common, writes string
			switch auth.Kind {
			case "browser":
				common = "sessions.Middleware()"
				if access == "admin" {
					common += ", sessions.RequireAdmin()"
				} else if access == "user" {
					common += ", copyauth.RequireRole(\"user\")"
				}
				writes = "[]core.Middleware{sessions.CSRF()}"
			case "bearer":
				common = "copyauth.Middleware()"
				if access == "admin" || access == "user" {
					common += ", copyauth.RequireRole(" + fmt.Sprintf("%q", access) + ")"
				}
				writes = "nil"
			}
			builder.WriteString("\tapp.ResourceWithMiddleware(" + target +
				", []core.Middleware{" + common + "}, " + writes + ")\n")
		}
	}
	builder.WriteString("}\n")
	source, err := format.Source([]byte(builder.String()))
	if err != nil {
		return fmt.Errorf("copytygo: generated resource route syntax: %w", err)
	}
	if err := os.WriteFile(filepath.Join(root, "routes", "resources.go"), source, 0644); err != nil {
		return err
	}
	return ensureGeneratedResourceCall(filepath.Join(root, "routes", "web.go"))
}

func ensureGeneratedResourceCall(path string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	content := string(raw)
	if strings.Contains(content, "RegisterGeneratedResources(app)") {
		return nil
	}
	index := strings.Index(content, "func Register(app *core.Application) {")
	if index < 0 {
		return fmt.Errorf("copytygo: routes.Register function not found")
	}
	insertAt := index + len("func Register(app *core.Application) {")
	content = content[:insertAt] + "\n    RegisterGeneratedResources(app)" + content[insertAt:]
	return os.WriteFile(path, []byte(content), 0644)
}

func projectModule(path string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "module ") {
			module := strings.TrimSpace(strings.TrimPrefix(line, "module "))
			if module != "" {
				return module, nil
			}
		}
	}
	return "", fmt.Errorf("copytygo: module path not found in go.mod")
}
